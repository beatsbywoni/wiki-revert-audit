"""보충자료(Supplementary Material) v0.2 를 04_output 의 CSV 에서 생성한다.

출력  05_manuscript/supplement_v0.2.md  (표 S1~S8, 그림 S1~S2 캡션)
"""
import os
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
O = os.path.join(ROOT, "04_output"); M = os.path.join(ROOT, "05_manuscript")
WIKIS = ["enwiki", "itwiki", "kowiki", "dewiki", "plwiki", "frwiki", "jawiki"]
WL = {"W12h": "12 h", "W24h": "24 h", "W48h": "48 h", "W7d": "7 d", "W30d": "30 d", "W180d": "180 d", "Winf": "unbounded"}


def md(df, floatfmt=".3f"):
    return df.to_markdown(floatfmt=floatfmt)


def main():
    L = ["# Supplementary Material", "",
         "Which reverts count? Successor filtering and observation windows in Wikipedia revert-based metrics", "",
         "All tables are generated by `03_pipeline/12_supplement.py` from the released aggregates in `04_output/`. "
         "Editions are ordered by the bot-and-tool share of first reverts. Confirmatory editions: jawiki, plwiki, itwiki.", ""]

    win = pd.read_csv(os.path.join(O, "robust_cross_windows.csv"))
    order = ["W12h", "W24h", "W48h", "W7d", "W30d", "W180d", "Winf"]
    L += ["## Table S1. Filter effect by observation window (replace variant, F2), R(W) and substitution S(W)", "",
          "Δ in percentage points from the 60,000-anchor samples (all anchors in kowiki); R(W) = Δ(W)/Δ(24 h); "
          "S(W) = 1 − Δ(replace, W)/Δ(strict, W) on the same sample.", ""]
    for val, lab, fmt in [("delta_replace_pp", "Δ(F2 replace, W), pp", ".2f"), ("R_vs_24h", "R(W)", ".3f"), ("S", "S(W)", ".3f")]:
        p = win.pivot(index="W", columns="wiki", values=val).loc[order, WIKIS]; p.index = [WL[i] for i in p.index]
        L += [f"**{lab}**", "", md(p, fmt), ""]

    var = pd.read_csv(os.path.join(O, "robust_cross_variants.csv"))
    L += ["## Table S2. Strict filter effect by definition of the excluded class (24-hour window, all primary anchors)", "",
          "Δ = p(F0) − p(F) in percentage points, 95 percent analytic interval in Table S2 data file. "
          "F1h/F1c: bot flag from the historical / current column only; F1fast and F2fast additionally treat registered non-bot reverts within 5 seconds as bots; "
          "F2s adds `mw-undo` to the tool tags; F3 additionally excludes anonymous reverters.", ""]
    p = var[var.W == "W24h"].pivot(index="variant", columns="wiki", values="delta_pp")[WIKIS]
    L += [md(p, ".2f"), ""]
    p = var[var.W == "Winf"].pivot(index="variant", columns="wiki", values="delta_pp")[WIKIS]
    L += ["Unbounded window:", "", md(p, ".2f"), ""]

    coh = pd.read_csv(os.path.join(O, "robust_cross_cohorts.csv"))
    L += ["## Table S3. Cohort variants: relative strict filter effect Δ(F2, 24 h)/p(F0, 24 h) and cohort size", ""]
    p = coh[coh.W == "W24h"].pivot(index="cohort", columns="wiki", values="rel_delta")[WIKIS]
    n = coh[coh.W == "W24h"].pivot(index="cohort", columns="wiki", values="n")[WIKIS]
    L += [md(p, ".3f"), "", "Anchors per cohort:", "", md(n, ".0f"), ""]

    tst = pd.read_csv(os.path.join(O, "robust_cross_tests.csv"))
    L += ["## Table S4. Normal approximations to the registered one-sided tests, with Holm adjustment within edition", "",
          "The registered tests are bootstrap bounds (reported in the main text); the normal approximation uses the analytic standard error of the paired "
          "difference (H1), the delta method (H2) and the log odds-ratio variance (H4). H3 is a descriptive agreement criterion and is not a test.", ""]
    t = tst[["wiki", "test", "estimate", "se", "p_one_sided", "p_holm"]].copy()
    t["p_one_sided"] = t["p_one_sided"].map(lambda x: "< .001" if x < .001 else f"{x:.3f}")
    t["p_holm"] = t["p_holm"].map(lambda x: "< .001" if x < .001 else f"{x:.3f}")
    L += [t.to_markdown(index=False, floatfmt=".3f"), ""]

    lg = pd.read_csv(os.path.join(O, "robust_cross_logit.csv"))
    L += ["## Table S5. Logistic regression of reverted status on filter and window (replace sample, long format), editor-clustered standard errors", "",
          "Reference cell F0 at 24 h. Rows: anchors × 3 filters × 3 windows (about 540,000 per edition; 428,661 in kowiki); clusters = editors. "
          "Coefficients on the log-odds scale; cluster-robust (CR1) standard errors in parentheses.", ""]
    terms = ["const", "F1r", "F2r", "W7d", "Winf", "F1r_x_W7d", "F1r_x_Winf", "F2r_x_W7d", "F2r_x_Winf"]
    c = lg.pivot(index="term", columns="wiki", values="coef").loc[terms, WIKIS]
    s = lg.pivot(index="term", columns="wiki", values="se_cluster").loc[terms, WIKIS]
    tab = c.round(3).astype(str) + " (" + s.round(3).astype(str) + ")"
    L += [tab.to_markdown(), ""]

    alt = pd.read_csv(os.path.join(O, "robust_kowiki_anchor_alt.csv"))
    L += ["## Table S6. kowiki: anchor definition (first edit, registered) versus first main-namespace edit (pilot definition), strict F2", "",
          alt.to_markdown(index=False, floatfmt=".3f"), ""]
    sg = pd.read_csv(os.path.join(O, "robust_kowiki_surge.csv"))
    L += ["**Table S6b.** kowiki with and without the June 2023 to December 2024 period of elevated newcomer inflow.", "",
          sg.to_markdown(index=False, floatfmt=".3f"), ""]

    sim = pd.read_csv(os.path.join(O, "simulation_window_ratio.csv")).dropna()
    g = sim.groupby(["p_human_follow_after_bot", "human_delay_median_s"])["R_inf_over_24h"].agg(["mean", "min", "max"]).reset_index()
    g["human_delay_median_s"] = g["human_delay_median_s"].map({600: "10 min", 3600: "1 h", 86400: "1 d", 604800: "7 d"})
    L += ["## Table S7. Simulation: R = Δ(∞)/Δ(24 h) as a function of the human re-revert probability after an excluded fast revert and the median human delay", "",
          "Grid over revert base rate (.10, .25, .40), excluded-actor share (0 to .8) and excluded-actor speed (5 to 60 s); R is averaged over those "
          "parameters (min and max shown) because they do not affect it. Observed R in the seven editions: .78 to .92.", "",
          g.rename(columns={"p_human_follow_after_bot": "p(human re-revert)", "human_delay_median_s": "median human delay"}).to_markdown(index=False, floatfmt=".3f"), ""]

    tags = pd.read_csv(os.path.join(O, "tag_availability_by_wiki.csv"))
    L += ["## Table S8. Change-tag availability on reverting revisions, by edition and year (all namespaces, all users)", "",
          "Counts of reverting revisions carrying each tag. `twinkle` is tagged only in enwiki from September 2020; `huggle` tagging in enwiki is nearly absent in 2021 and 2022.", ""]
    for tag in ["mw-rollback", "huggle", "twinkle", "mw-undo", "mw-reverted"]:
        t = tags[tags.tag == tag].set_index("wiki").loc[WIKIS, [f"y{y}" for y in range(2018, 2027)]]
        t.columns = [c[1:] for c in t.columns]
        L += [f"**{tag}**", "", t.to_markdown(floatfmt=",.0f"), ""]

    L += ["## Figure S1. Retention odds ratio in the nine strict cells, by edition", "",
          "![](figures/FigureS1.png)", "",
          "Odds ratio of retention (an edit on days 2 to 60) for reverted versus non-reverted anchors, with 95 percent intervals, for the three filters "
          "(F0 all reverts, F1 excluding bots, F2 excluding bots and tools) in the 24-hour, 7-day and unbounded windows.", "",
          "## Figure S2. Monthly first-edit anchors and 24-hour revert rates, kowiki, enwiki and jawiki, 2019 to March 2026", "",
          "![](figures/FigureS2.png)", "",
          "Upper panel: anchors per month relative to each edition's median. Lower panel: share of anchors reverted within 24 hours under F0 (solid) and F2 strict (dashed). "
          "The kowiki inflow and revert-rate rise from mid-2023 to the end of 2024 is discussed in the Results; the drop in enwiki's F2 line in September 2020 marks the start of Twinkle tagging.", ""]
    with open(os.path.join(M, "supplement_v0.2.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(L))
    print("supplement written:", len("\n".join(L).split()), "words")


if __name__ == "__main__":
    main()
