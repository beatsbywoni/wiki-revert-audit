"""Supplementary Material for manuscript v0.3, generated from released aggregates in 04_output/.

Output: 05_manuscript/supplement_v0.3.md
"""
import os
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
O = os.path.join(ROOT, "04_output"); M = os.path.join(ROOT, "05_manuscript")
WIKIS = ["enwiki", "itwiki", "kowiki", "dewiki", "plwiki", "frwiki", "jawiki"]
NAME = {"enwiki": "English", "itwiki": "Italian*", "kowiki": "Korean", "dewiki": "German", "plwiki": "Polish*", "frwiki": "French", "jawiki": "Japanese*"}
WL = {"W24h": "24 h", "W7d": "7 d", "W180d": "180 d", "Winf": "unbounded", "W12h": "12 h", "W48h": "48 h", "W30d": "30 d"}
CL = {"bot": "Bot", "tool": "One-click tool", "manual_other": "Other registered, manual", "anon": "Unregistered", "self": "Self",
      "bot_or_tool": "Bot or one-click tool", "any_manual": "Manual, by another editor", "any": "Any revert", "all": "All reverters"}


def piv(df, index, values, fmt=".3f", cols="wiki", order=None):
    p = df.pivot(index=index, columns=cols, values=values)[WIKIS]
    p.columns = [NAME[c] for c in p.columns]
    if order: p = p.loc[[o for o in order if o in p.index]]
    return p.to_markdown(floatfmt=fmt)


def main():
    L = ["# Supplementary Material", "",
         "Which reverts count? Reverter populations, attribution rules and observation windows behind a Wikipedia indicator of information quality work", "",
         "Tables are generated by `03_pipeline/17_supplement_v03.py` from the aggregates in `04_output/` of the public repository. Editions marked * were held out "
         "for the registered tests. Dump rule: the history dumps' unbounded identity-revert rule. Radius rule: the same hashes with the 15-revision radius of the mwreverts library.", ""]

    pr = os.path.join(O, "practice_review.csv")
    if os.path.exists(pr):
        R = pd.read_csv(pr); R = R[R.in_tallies == "yes"]
        keep = [c for c in ["short_cite", "venue", "editions", "role", "detection", "radius_or_rule", "bot_reverts", "tool_reverts", "self_reverts", "window",
                            "sensitivity_over_revert_choices", "evidence_level"] if c in R.columns]
        L += ["## Table S1. Structured review of practice: how studies using a revert-based measure operationalise it", "",
              "One row per study. \"Not stated\" means that no statement was found in the methods text read. Evidence level: A, establishing sentence re-verified in the "
              "full text; B, taken from a first coder's extract; C, metadata or abstract only. The full table with the establishing sentences, URLs and references is "
              "`04_output/practice_review.csv`.", "", R[keep].to_markdown(index=False), "",
              "**References for Table S1**", ""] + [__import__("re").sub(r"\s*\[[^\]]*\]\s*$", "", str(x)).strip() + "\n" for x in sorted(R.apa_reference.dropna())]

    c = pd.read_csv(os.path.join(O, "rev_composition.csv"))
    L += ["## Table S2. Composition of first reverts of newcomer first edits (dump rule, full cohorts)", ""]
    for coh in ["2019+", "2021+"]:
        for w in ["W24h", "Winf"]:
            g = c[(c.cohort == coh) & (c.W == w)].set_index("wiki").loc[WIKIS]
            t = pd.DataFrame({"Edition": [NAME[x] for x in g.index], "First edits": g.n.map("{:,}".format).values, "p reverted": g.p_F0.round(3).values})
            for k in ["bot", "tool", "manual_other", "anon", "self"]:
                t[CL[k]] = [f"{a:.3f} [{b:.3f}, {d:.3f}]" for a, b, d in zip(g[f"share_{k}"], g[f"share_{k}_lo"], g[f"share_{k}_hi"])]
            L += [f"**First edits {coh.replace('+', ' onward')}, window {WL[w]}.** Shares of first reverts with 95 percent Wilson intervals.", "", t.to_markdown(index=False), ""]

    L += ["## Table S3. Change in the revert rate when a class of first reverts is recoded as not reverted (percentage points; identity: share times rate)", ""]
    for coh in ["2019+", "2021+"]:
        g = c[(c.cohort == coh) & (c.W == "W24h")].set_index("wiki").loc[WIKIS]
        t = pd.DataFrame({"Edition": [NAME[x] for x in g.index]})
        for k, lab in [("bot", "Bots"), ("tool", "One-click tools"), ("self", "Self-reverts"), ("anon", "Unregistered reverters"), ("undo", "Undo-button reverts (if counted as a tool)")]:
            t[lab] = g[f"delta_excl_{k}_pp"].round(2).values
        t["Undo share of manual reverts"] = g.share_undo_button_among_manual.round(3).values
        L += [f"**First edits {coh.replace('+', ' onward')}, 24-hour window.**", "", t.to_markdown(index=False), ""]

    f = pd.read_csv(os.path.join(O, "rev_followup.csv")); w = pd.read_csv(os.path.join(O, "rev_window.csv"))
    L += ["## Table S4. Follow-up manual reverts by class of first reverter, and the window ratio R, under two attribution rules (page-history samples)", ""]
    for rule, rn in [("d3", "Dump rule"), ("d3r", "Radius rule")]:
        for wn in ["W24h", "W7d", "W180d", "Winf"]:
            g = f[(f.rule == rule) & (f.W == wn)]
            L += [f"**{rn}, window {WL[wn]}.** Share of first edits first reverted by the class shown that were later reverted manually by another editor.", "",
                  piv(g.assign(first_class=g.first_class.map(CL)), "first_class", "followup", order=[CL[k] for k in ["bot_or_tool", "any_manual", "bot", "tool", "manual_other", "anon", "self"]]), ""]
        g = f[(f.rule == rule) & (f.W == "Winf") & (f.first_class.isin(["bot_or_tool", "any_manual"]))]
        for col, lab in [("followup_after_reinstatement", "after the first edit's content was reinstated"), ("followup_immediate_deeper", "immediately, restoring a still earlier state"),
                         ("followup_other", "after other intervening edits")]:
            L += [f"**{rn}, unbounded: follow-up {lab}** (share of first edits first reverted by the class).", "",
                  piv(g.assign(first_class=g.first_class.map(CL)), "first_class", col), ""]
    t = w.assign(R_ci=[f"{r:.3f} [{a:.3f}, {b:.3f}]" for r, a, b in zip(w.R, w.lo, w.hi)], rule=w.rule.map({"d3": "Dump rule", "d3r": "Radius rule"}),
                 key=lambda d: d.rule + ", " + d.ratio.map({"Winf/W24h": "unbounded / 24 h", "W180d/W24h": "180 d / 24 h"}))
    L += ["**Window ratio R** (replace effect of excluding bots and tools at the longer window divided by the effect within 24 hours; 2,000 bootstrap resamples of editors).", "",
          piv(t, "key", "R_ci", fmt=""), ""]

    r = pd.read_csv(os.path.join(O, "rev_retention.csv")); r = r[~r.first_revert_class.str.startswith("registered")]
    r["cell"] = [f"{s:.3f}; OR {o:.2f} [{a:.2f}, {b:.2f}]; n = {n:,}" for s, o, a, b, n in zip(r.retained_share, r.OR_vs_not_reverted, r.lo, r.hi, r.n_class)]
    L += ["## Table S5. Retention (an edit on days 2 to 60) by who made the first revert within 24 hours", "",
          "Cells: share retained; odds ratio against newcomers not reverted within 24 hours with 95 percent Woolf interval (0.5 added to each cell); number of newcomers. "
          "Classes with fewer than 30 newcomers are omitted.", "",
          piv(r.assign(first_revert_class=r.first_revert_class.map(CL)), "first_revert_class", "cell", fmt="", order=[CL[k] for k in ["any", "bot", "tool", "manual_other", "anon", "self"]]), "",
          "Share retained among newcomers not reverted within 24 hours:", "",
          pd.DataFrame({NAME[k]: [round(v, 3)] for k, v in r.groupby("wiki").retained_share_not_reverted.first().loc[WIKIS].items()}).to_markdown(index=False), ""]

    t = pd.read_csv(os.path.join(O, "rev_taggap.csv"))
    t["cell"] = [f"{u:.3f} [{a:.3f}, {b:.3f}]; n = {n:,}" for u, a, b, n in zip(t.untagged, t.lo, t.hi, t.n)]
    L += ["## Table S6. Tag coverage: radius-rule reverts whose reverted first edit carries no `mw-reverted` tag, first edits from October 2020", "",
          "Patrolling regime: English, Korean, Japanese none; German, Polish FlaggedRevs; Italian, French recent-changes patrolling. Cells: untagged share with 95 percent Wilson interval; number of reverts.", "",
          piv(t.assign(reverter_class=t.reverter_class.map(CL)), "reverter_class", "cell", fmt="", order=[CL[k] for k in ["all", "bot", "tool", "manual_other", "anon", "self"]]), ""]

    h = pd.read_csv(os.path.join(O, "rev_h4_boot2000.csv")).set_index("wiki").loc[WIKIS]
    rows = []
    for wk in ["jawiki", "plwiki", "itwiki"]:
        cf = pd.read_csv(os.path.join(O, f"{wk}_confirmatory.csv"))
        rows.append(cf.assign(edition=NAME[wk]))
    L += ["## Table S7. Registered tests in the held-out editions, as produced by the registered code", "",
          "Bootstrap replicates in the registered code: 2,000 for H1 and H2, 500 for H4 (the manuscript reports H4 intervals recomputed with 2,000 replicates, below). "
          "Holm adjustment across the three tests per edition does not change any decision.", "",
          pd.concat(rows).set_index("edition").T.to_markdown(floatfmt=".3f"), "",
          "**H4 recomputed with 2,000 paired bootstrap replicates (all editions).**", "",
          pd.DataFrame({"Edition": [NAME[x] for x in h.index], "max/min odds ratio": h.ratio.round(3).values,
                        "95% interval": [f"[{a:.3f}, {b:.3f}]" for a, b in zip(h.lo, h.hi)], "one-sided 95% lower bound": h.one_sided_lower_95.round(3).values}).to_markdown(index=False), ""]

    tags = pd.read_csv(os.path.join(O, "tag_availability_by_wiki.csv"))
    L += ["## Table S8. Change tags on reverting revisions by edition and year (all namespaces)", ""]
    for tag in ["mw-rollback", "huggle", "twinkle", "mw-undo"]:
        g = tags[tags.tag == tag].set_index("wiki").loc[WIKIS, [f"y{y}" for y in range(2018, 2027)]]
        g.columns = [x[1:] for x in g.columns]; g.index = [NAME[x] for x in g.index]
        L += [f"**{tag}**", "", g.to_markdown(floatfmt=",.0f"), ""]

    coh = pd.read_csv(os.path.join(O, "robust_cross_cohorts.csv"))
    L += ["## Table S9. Cohort variants: bot-or-tool share of first reverts within 24 hours", "",
          piv(coh[coh.W == "W24h"], "cohort", "rel_delta"), "",
          "## Figure S1. Odds ratio of retention in the nine registered cells, by edition", "", "![](figures/FigureS1.png)", "",
          "Reverted versus non-reverted first edits under three reverter filters (all reverts; without bots; without bots and one-click tools, strict recoding) and three windows. "
          "The movement across cells is compositional (see main text).", "",
          "## Figure S2. Monthly newcomer first edits and 24-hour revert rates in Korean, English and Japanese, 2019 to March 2026", "", "![](figures/FigureS2.png)", "",
          "Upper panel: first edits per month relative to the edition's median. Lower panel: share reverted within 24 hours, all reverts (solid) and without bots and one-click tools (dashed). "
          "The drop of the dashed English line in September 2020 marks the start of Twinkle tagging.", ""]
    with open(os.path.join(M, "supplement_v0.3.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(L))
    print("supplement v0.3 written")


if __name__ == "__main__":
    main()
